// Parses the GPX files in gpx/ into js/course-data.js, a plain classic
// script (window.courseData = {...}) — no fetch/build step is needed at
// site runtime, which also keeps the site working when opened directly via
// file:// (ES module + fetch are both blocked by Chrome's CORS rules there).
//
// Run this again after replacing a GPX file: node scripts/generate-course-data.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

const files = {
  swim: "gpx/Natation-champex.gpx",
  bike: "gpx/35km-champex--_-Fouly.gpx",
  run: "gpx/Fouly-6km.gpx",
};

function parseGpx(text) {
  let matches = [...text.matchAll(/<rtept lat="([-0-9.]+)" lon="([-0-9.]+)">(?:(?!<\/rtept>)[\s\S])*?<ele>([-0-9.]+)<\/ele>/g)];
  if (matches.length === 0) {
    matches = [...text.matchAll(/<trkpt lat="([-0-9.]+)" lon="([-0-9.]+)">(?:(?!<\/trkpt>)[\s\S])*?<ele>([-0-9.]+)<\/ele>/g)];
  }
  return matches.map((m) => ({ lat: parseFloat(m[1]), lon: parseFloat(m[2]), ele: parseFloat(m[3]) }));
}

const EARTH_RADIUS = 6371000;
const toRad = (d) => (d * Math.PI) / 180;
function haversine(lat1, lon1, lat2, lon2) {
  const dphi = toRad(lat2 - lat1);
  const dlambda = toRad(lon2 - lon1);
  const a = Math.sin(dphi / 2) ** 2 + Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dlambda / 2) ** 2;
  return 2 * EARTH_RADIUS * Math.asin(Math.sqrt(a));
}

function computeStats(points) {
  let distance = 0, gain = 0, loss = 0, minEle = Infinity, maxEle = -Infinity;
  for (let i = 0; i < points.length; i++) {
    const p = points[i];
    minEle = Math.min(minEle, p.ele);
    maxEle = Math.max(maxEle, p.ele);
    if (i > 0) {
      const prev = points[i - 1];
      distance += haversine(prev.lat, prev.lon, p.lat, p.lon);
      const de = p.ele - prev.ele;
      if (de > 0) gain += de;
      else loss += -de;
    }
  }
  return { distanceKm: distance / 1000, gain, loss, minEle, maxEle };
}

const data = {};
for (const [id, rel] of Object.entries(files)) {
  const text = fs.readFileSync(path.join(root, rel), "utf-8");
  const points = parseGpx(text);
  if (points.length === 0) throw new Error(`No points parsed from ${rel}`);
  data[id] = { points, stats: computeStats(points) };
}

const out = `// AUTO-GENERATED by scripts/generate-course-data.mjs — do not edit by hand.
// Re-run that script after replacing a GPX file in gpx/.
window.courseData = ${JSON.stringify(data)};
`;
fs.writeFileSync(path.join(root, "js/course-data.js"), out);

console.log("Wrote js/course-data.js");
for (const [id, d] of Object.entries(data)) {
  console.log(`  ${id}: ${d.points.length} points, ${d.stats.distanceKm.toFixed(2)} km`);
}
